function getStoredToken(provider) {
  // See integrations/secretStore.js for the encrypted-at-rest token store.
  return process.env[`${provider.toUpperCase()}_ACCESS_TOKEN`] || null;
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}
